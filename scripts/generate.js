/**
 * Embeds the Windows migration SQL files and the en-US resource strings into
 * TypeScript modules so the React Native bundler can include them.
 *
 *   src/data/sql/migrations.generated.ts   - ordered { version, name, sql } list
 *   src/ui/strings.generated.ts            - the Resources.resw string table
 *
 * The .sql files are copied 1:1 from
 *   src/DietTracker.Infrastructure/Database/Migrations (Windows repository)
 * and the .resw from
 *   src/DietTracker.App/Resources/Strings/en-US/Resources.resw
 * so the migration history and every UI string stay byte-compatible with Windows.
 *
 * Run:  node scripts/generate.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MIGRATIONS_DIR = path.join(ROOT, 'src', 'data', 'migrations');
const OUT_SQL_DIR = path.join(ROOT, 'src', 'data', 'sql');
const RESW = path.join(ROOT, '..', 'src', 'DietTracker.App', 'Resources', 'Strings', 'en-US', 'Resources.resw');
const OUT_STRINGS = path.join(ROOT, 'src', 'ui', 'strings.generated.ts');

// Escapes a string so it can sit inside a TS template literal untouched.
function escapeTemplate(sql) {
  return sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

// XML entity decoding for resw values. Ampersand is handled by the alternation
// itself (no second pass), so there is no ordering hazard.
function decodeXml(value) {
  const named = {
    lt: '<',
    gt: '>',
    quot: '"',
    apos: "'",
    amp: '&',
  };
  return value
    .replace(/&#x([0-9a-fA-F]+);/g, (m, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (m, dec) => String.fromCodePoint(Number(dec)))
    .replace(/&(lt|gt|quot|apos|amp);/g, (m, name) => named[name]);
}

function generateMigrations() {
  const files = fs
    .readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort(); // 0001_..., 0002_... - lexicographic order == chronological order

  const entries = files.map((file) => {
    const match = /^(\d{4})_/.exec(file);
    if (!match) {
      throw new Error('Migration file name must start with a 4-digit version: ' + file);
    }
    return {
      version: Number(match[1]),
      name: file,
      sql: fs.readFileSync(path.join(MIGRATIONS_DIR, file), 'utf8'),
    };
  });

  for (let i = 0; i < entries.length; i += 1) {
    if (entries[i].version !== i + 1) {
      throw new Error('Migration versions must be contiguous from 1 (bad version ' + entries[i].version + ').');
    }
  }

  const body = entries
    .map((e) => '  {\n    version: ' + e.version + ',\n    name: ' + JSON.stringify(e.name) + ',\n    sql: `' + escapeTemplate(e.sql) + '`,\n  },')
    .join('\n');

  const output =
    '// AUTO-GENERATED by scripts/generate.js - do not edit by hand.\n' +
    '// Source of truth: src/data/migrations/*.sql (copied verbatim from the Windows repository).\n\n' +
    "import type { Migration } from '../database';\n\n" +
    'export const MIGRATIONS: Migration[] = [\n' + body + '\n];\n';

  fs.mkdirSync(OUT_SQL_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_SQL_DIR, 'migrations.generated.ts'), output, 'utf8');
  console.log('migrations.generated.ts: ' + entries.length + ' migrations embedded.');
}

function generateStrings() {
  if (!fs.existsSync(RESW)) {
    console.warn('strings: resw not found at ' + RESW + ' - skipping (mobile-only checkout).');
    return;
  }

  const xml = fs.readFileSync(RESW, 'utf8');
  const pattern = /<data name="([^"]+)"[^>]*>\s*<value>([\s\S]*?)<\/value>\s*<\/data>/g;
  const entries = [];
  const seen = new Set();
  let match = pattern.exec(xml);
  while (match !== null) {
    if (!seen.has(match[1])) {
      seen.add(match[1]);
      entries.push([match[1], decodeXml(match[2])]);
    }
    match = pattern.exec(xml);
  }

  const body = entries.map((e) => '  ' + JSON.stringify(e[0]) + ': ' + JSON.stringify(e[1]) + ',').join('\n');

  const output =
    '// AUTO-GENERATED by scripts/generate.js - do not edit by hand.\n' +
    '// Source of truth: src/DietTracker.App/Resources/Strings/en-US/Resources.resw (Windows app).\n' +
    '// English only - there is no interface language switch (spec 1.5 / 2.5).\n\n' +
    'export const STRINGS: Record<string, string> = {\n' + body + '\n};\n';

  fs.mkdirSync(path.dirname(OUT_STRINGS), { recursive: true });
  fs.writeFileSync(OUT_STRINGS, output, 'utf8');
  console.log('strings.generated.ts: ' + entries.length + ' strings embedded.');
}

generateMigrations();
generateStrings();